CREATE TABLE VENTA (
    ID_VENTA INT NOT NULL,
    FECHA_VENTA DATE NOT NULL,
    ID_TIENDA INT NOT NULL,
    ID_EMPLEADO INT NOT NULL,
    ID_CLIENTE INT NOT NULL,
    ID_ES_VENTA INT NOT NULL,

    CONSTRAINT PK_VENTA
        PRIMARY KEY (ID_VENTA),

    CONSTRAINT FK_VENTA_TIENDA
        FOREIGN KEY (ID_TIENDA)
        REFERENCES TIENDA(ID_TIENDA),

    CONSTRAINT FK_VENTA_EMPLEADO
        FOREIGN KEY (ID_EMPLEADO)
        REFERENCES EMPLEADO(ID_EMPLEADO),

    CONSTRAINT FK_VENTA_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE(ID_CLIENTE),

    CONSTRAINT FK_VENTA_ESTADO
        FOREIGN KEY (ID_ES_VENTA)
        REFERENCES ESTADO_VENTA(ID_ES_VENTA)
);
GO


CREATE TABLE DESGLOSE_VENTA (
    ID_VENTA INT NOT NULL,
    ID_PRO INT NOT NULL,
    CANTIDAD_DES_VENTA INT NOT NULL,
    PRECIO_UNITARIO_DES_VENTA DECIMAL(10,2) NOT NULL,
    SUBTOTAL_DES_VENTA DECIMAL(12,2) NOT NULL,

    CONSTRAINT PK_DESGLOSE_VENTA
        PRIMARY KEY (ID_VENTA, ID_PRO),

    CONSTRAINT CK_DES_CANT_POS
        CHECK (CANTIDAD_DES_VENTA > 0),

    CONSTRAINT CK_DES_PRECIO_POS
        CHECK (PRECIO_UNITARIO_DES_VENTA > 0),

    CONSTRAINT CK_DES_SUBTOTAL_POS
        CHECK (SUBTOTAL_DES_VENTA > 0),

    CONSTRAINT CK_DES_SUBTOTAL_CALC
        CHECK (
            SUBTOTAL_DES_VENTA =
            CANTIDAD_DES_VENTA * PRECIO_UNITARIO_DES_VENTA
        ),

    CONSTRAINT FK_DES_VENTA
        FOREIGN KEY (ID_VENTA)
        REFERENCES VENTA(ID_VENTA),

    CONSTRAINT FK_DES_PRODUCTO
        FOREIGN KEY (ID_PRO)
        REFERENCES PRODUCTO(ID_PRO)
);
GO


CREATE TABLE PAGO (
    ID_PAGO INT NOT NULL,
    MONTO_PAGO DECIMAL(12,2) NOT NULL,
    ID_VENTA INT NOT NULL,
    ID_MET_PAGO INT NOT NULL,

    CONSTRAINT PK_PAGO
        PRIMARY KEY (ID_PAGO),

    CONSTRAINT CK_PAGO_MONTO_POS
        CHECK (MONTO_PAGO > 0),

    CONSTRAINT FK_PAGO_VENTA
        FOREIGN KEY (ID_VENTA)
        REFERENCES VENTA(ID_VENTA),

    CONSTRAINT FK_PAGO_METODO
        FOREIGN KEY (ID_MET_PAGO)
        REFERENCES METODO_PAGO(ID_MET_PAGO)
);
GO


