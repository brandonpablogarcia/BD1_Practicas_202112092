GO


CREATE TABLE CATALOGO_PRODUCTO (
    ID_TIENDA INT NOT NULL,
    ID_PRO INT NOT NULL,
    PRECIO_VIGENTE_CAT_PRO DECIMAL(10,2) NOT NULL,
    EXISTENCIA_ACTUAL_CAT_PRO INT NOT NULL,

    CONSTRAINT PK_CATALOGO_PRODUCTO
        PRIMARY KEY (ID_TIENDA, ID_PRO),

    CONSTRAINT CK_CAT_PRECIO_POS
        CHECK (PRECIO_VIGENTE_CAT_PRO > 0),

    CONSTRAINT CK_CAT_EXIST_NO_NEG
        CHECK (EXISTENCIA_ACTUAL_CAT_PRO >= 0),

    CONSTRAINT FK_CAT_TIENDA
        FOREIGN KEY (ID_TIENDA)
        REFERENCES TIENDA(ID_TIENDA),

    CONSTRAINT FK_CAT_PRODUCTO
        FOREIGN KEY (ID_PRO)
        REFERENCES PRODUCTO(ID_PRO)
);
GO

