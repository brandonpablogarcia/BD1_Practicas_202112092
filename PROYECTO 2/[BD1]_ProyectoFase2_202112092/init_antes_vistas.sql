CREATE TABLE PERSONA (
    ID_PERSONA INT NOT NULL,
    NOMBRE_PERSONA NVARCHAR(100) NOT NULL,
    APELLIDO_PERSONA NVARCHAR(100) NOT NULL,
    TELEFONO_PERSONA NVARCHAR(20) NOT NULL,
    CORREO_PERSONA NVARCHAR(150) NULL,
    DIRECCION_PERSONA NVARCHAR(200) NOT NULL,
    ID_MUN INT NOT NULL,

    CONSTRAINT PK_PERSONA
        PRIMARY KEY (ID_PERSONA),

    CONSTRAINT FK_PERSONA_MUN
        FOREIGN KEY (ID_MUN)
        REFERENCES MUNICIPIO(ID_MUN)
);
GO

CREATE UNIQUE INDEX UX_PERSONA_CORREO
ON PERSONA(CORREO_PERSONA)
WHERE CORREO_PERSONA IS NOT NULL;
GO

CREATE TABLE TIENDA (
