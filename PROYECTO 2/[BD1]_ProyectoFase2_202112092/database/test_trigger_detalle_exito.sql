USE ComercialLaEstrella;
GO

DECLARE @ID_TIENDA INT;
DECLARE @ID_PRO INT;
DECLARE @STOCK_ANTES INT;
DECLARE @PRECIO DECIMAL(10,2);
DECLARE @ID_EMPLEADO INT;
DECLARE @ID_CLIENTE INT;
DECLARE @ID_ESTADO INT;
DECLARE @ID_VENTA INT;

-- Elegimos un producto que tenga al menos una unidad.
SELECT TOP 1
    @ID_TIENDA = cp.ID_TIENDA,
    @ID_PRO = cp.ID_PRO,
    @STOCK_ANTES = cp.EXISTENCIA_ACTUAL_CAT_PRO,
    @PRECIO = cp.PRECIO_VIGENTE_CAT_PRO
FROM dbo.CATALOGO_PRODUCTO cp
WHERE cp.EXISTENCIA_ACTUAL_CAT_PRO >= 1
AND EXISTS (
    SELECT 1
    FROM dbo.EMPLEADO e
    WHERE e.ID_TIENDA = cp.ID_TIENDA
)
ORDER BY cp.ID_TIENDA, cp.ID_PRO;

SELECT TOP 1
    @ID_EMPLEADO = ID_EMPLEADO
FROM dbo.EMPLEADO
WHERE ID_TIENDA = @ID_TIENDA;

SELECT TOP 1
    @ID_CLIENTE = ID_CLIENTE
FROM dbo.CLIENTE
ORDER BY ID_CLIENTE;

SELECT TOP 1
    @ID_ESTADO = ID_ES_VENTA
FROM dbo.ESTADO_VENTA
WHERE UPPER(NOMBRE_ES_VENTA) = 'REGISTRADA';

SELECT
    @ID_VENTA = ISNULL(MAX(ID_VENTA), 0) + 1
FROM dbo.VENTA;


BEGIN TRANSACTION;


SELECT
    @ID_TIENDA AS ID_TIENDA,
    @ID_PRO AS ID_PRODUCTO,
    @STOCK_ANTES AS STOCK_ANTES;


INSERT INTO dbo.VENTA (
    ID_VENTA,
    FECHA_VENTA,
    ID_TIENDA,
    ID_EMPLEADO,
    ID_CLIENTE,
    ID_ES_VENTA
)
VALUES (
    @ID_VENTA,
    CAST(GETDATE() AS DATE),
    @ID_TIENDA,
    @ID_EMPLEADO,
    @ID_CLIENTE,
    @ID_ESTADO
);


INSERT INTO dbo.DESGLOSE_VENTA (
    ID_VENTA,
    ID_PRO,
    CANTIDAD_DES_VENTA,
    PRECIO_UNITARIO_DES_VENTA,
    SUBTOTAL_DES_VENTA
)
VALUES (
    @ID_VENTA,
    @ID_PRO,
    1,
    @PRECIO,
    @PRECIO
);


SELECT
    EXISTENCIA_ACTUAL_CAT_PRO AS STOCK_DESPUES
FROM dbo.CATALOGO_PRODUCTO
WHERE ID_TIENDA = @ID_TIENDA
  AND ID_PRO = @ID_PRO;


-- La prueba no deja datos permanentes.
ROLLBACK TRANSACTION;


SELECT
    EXISTENCIA_ACTUAL_CAT_PRO AS STOCK_RESTAURADO
FROM dbo.CATALOGO_PRODUCTO
WHERE ID_TIENDA = @ID_TIENDA
  AND ID_PRO = @ID_PRO;
GO
